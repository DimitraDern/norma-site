const groups = ["Όλα", "Πλέγματα", "Ασφάλεια", "Υλικά", "Κατασκευές", "Εξοπλισμός"];

function ImageCarousel({ images, alt }) {
  const [index, setIndex] = useState(0);
  const hasMultiple = images.length > 1;

  function prev(e) {
    e.stopPropagation();
    setIndex((i) => (i === 0 ? images.length - 1 : i - 1));
  }
  function next(e) {
    e.stopPropagation();
    setIndex((i) => (i === images.length - 1 ? 0 : i + 1));
  }

  return (
    <div className="relative w-full h-40 border-b border-ink/10 overflow-hidden group">
      <img src={images[index]} alt={alt} className="w-full h-full object-cover" />
      {hasMultiple && (
        <>
          <button
            onClick={prev}
            aria-label="Προηγούμενη εικόνα"
            className="absolute left-1.5 top-1/2 -translate-y-1/2 w-7 h-7 rounded-full bg-ink/60 text-white flex items-center justify-center opacity-0 group-hover:opacity-100 transition-opacity"
          >
            ‹
          </button>
          <button
            onClick={next}
            aria-label="Επόμενη εικόνα"
            className="absolute right-1.5 top-1/2 -translate-y-1/2 w-7 h-7 rounded-full bg-ink/60 text-white flex items-center justify-center opacity-0 group-hover:opacity-100 transition-opacity"
          >
            ›
          </button>
          <div className="absolute bottom-2 left-0 right-0 flex justify-center gap-1.5">
            {images.map((_, i) => (
              <span
                key={i}
                className={`w-1.5 h-1.5 rounded-full ${i === index ? "bg-white" : "bg-white/40"}`}
              />
            ))}
          </div>
        </>
      )}
    </div>
  );
}

